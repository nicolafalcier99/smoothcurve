#!/usr/bin/env python3
"""Build dist/SmoothCurve.jsx: the one file that gets installed.

The four source files are plain scripts with top-level functions, so the tests can #include
them one by one. Here they are joined, in order, inside one function, so nothing leaks into
other scripts and the panel receives `this` (the dock panel EffectCraft hands it).

    python3 -I build.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
PARTS = ["core.js", "apply.js", "store.js", "ui.js"]

HEADER = """// SmoothCurve {version}: an easing curve panel for EffectCraft.
//
// Shape a curve with two handles (or pick one of 25 easings), press Apply, and it lands on the
// selected keyframes in one undo step. Keep your own curves in libraries and move them between
// computers as text or as a .curves.json file.
//
// Install: File > Scripts > Install ScriptUI Panel..., pick this file, then open it from the
// bottom of the Window menu. (Or copy it into Scripts/ScriptUI Panels in the settings folder.)
// Built and tested for EffectCraft 0.24.1. It uses only the documented After Effects-style
// scripting API; it makes no network requests and writes no file unless you ask it to.
//
// Copyright (c) 2026 Nicola Falcier. SPDX-License-Identifier: MIT OR Apache-2.0
// An independent community panel: not made or endorsed by the ArtCraft Team, and not
// affiliated with Flow for After Effects.
//
// The keyframe apply engine is taken from EffectCraft's bundled "Ease Presets.jsx" panel
// (extensions/scriptui-panels, tag v0.24.1, Copyright (c) 2026 ArtCraft Team and the EffectCraft
// contributors, MIT OR Apache-2.0); the rest is original work under the same terms. The idea
// of the panel follows Flow for After Effects; no code, file, artwork or preset of Flow was
// used. The built-in easing values are the public cubic-bezier forms of Robert Penner's
// easing functions (as in postcss-easings, MIT).
//
// This file is generated by build.py from src/. Change the sources, not this file.

(function smoothCurve(thisObj) {{
"""

FOOTER = """
  buildPanel(thisObj);
})(this);
"""


def main():
    src = {}
    for name in PARTS:
        text = open(os.path.join(ROOT, "src", name), encoding="utf-8").read()
        if re.search(r"^\s*(#include|//@include)", text, re.M):
            raise SystemExit("%s must not include other files (the build joins them)" % name)
        src[name] = text
    m = re.search(r'var SMOOTHCURVE_VERSION = "([^"]+)";', src["ui.js"])
    if not m:
        raise SystemExit("SMOOTHCURVE_VERSION not found in src/ui.js")
    out = [HEADER.format(version=m.group(1))]
    for name in PARTS:
        out.append("  // ===================================================================== src/%s\n" % name)
        for line in src[name].rstrip("\n").split("\n"):
            out.append(("  " + line if line else "") + "\n")
        out.append("\n")
    out.append(FOOTER.lstrip("\n"))
    text = "".join(out)
    os.makedirs(os.path.join(ROOT, "dist"), exist_ok=True)
    path = os.path.join(ROOT, "dist", "SmoothCurve.jsx")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("built %s (%d lines, %d bytes)" % (os.path.relpath(path, ROOT), text.count("\n"), len(text.encode("utf-8"))))


if __name__ == "__main__":
    sys.exit(main())
